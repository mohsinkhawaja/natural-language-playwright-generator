from .scenario import Opcode, parse_scenario

HEAD = """# Generated by intent_qa. Edit the scenario, then regenerate.
from playwright.sync_api import expect

from intent_qa.demo import open_demo


def test_order_scenario():
    with open_demo() as page:"""


def compile_scenario(source: str) -> str:
    plan = parse_scenario(source)
    statements = []
    for action in plan[1:]:
        target, value = repr(action.target), repr(action.value)
        match action.opcode:
            case Opcode.ENTER:
                statement = f"page.get_by_role('textbox', name={target}, exact=True).fill({value})"
            case Opcode.CLICK:
                statement = (
                    f"page.get_by_role('button', name={target}, exact=True).click()"
                )
            case Opcode.CHECK:
                locator = f"page.get_by_role('status', name={target}, exact=True)"
                statement = f"expect({locator}).to_have_text({value})"
            case _:
                raise AssertionError("Unexpected opcode in validated scenario")
        statements.append("        " + statement)
    return HEAD + "\n" + "\n".join(statements) + "\n"
